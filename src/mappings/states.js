/**
 * Gets the Salesforce state code that corresponds to the state's full name
 * 
 * @param {string} stateFullName
 * @returns {string} stateCode
 */
export function getStateCode(stateFullName) {
    if (!stateFullName || typeof stateFullName !== 'string') {
        throw new Error('State name must be a non-empty string');
    }

    const stateCode = STATE_DICT[stateFullName]

    if (!stateCode) {
        throw new Error(`No state code found for: ${stateFullName}`);
    }

    return stateCode;
}